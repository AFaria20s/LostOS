static const uint8_t unknown[GUI_FONT_HEIGHT] =
  {0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04};

static const uint8_t *glyph_for(char character) {
  if (character >= 'a' && character <= 'z')
    character -= 'a' - 'A';
  if (character >= 'A' && character <= 'Z')
    return letters[character - 'A'];
  if (character >= '0' && character <= '9')
    return digits[character - '0'];
  if (character == ' ')
    return 0;
  return unknown;
}

void gui_draw_char(uint32_t x, uint32_t y, char character, uint32_t scale,
                   uint32_t color) {
  const uint8_t *glyph = glyph_for(character);

  if (!glyph || scale == 0)
    return;
  for (uint32_t row = 0; row < GUI_FONT_HEIGHT; row++)
    for (uint32_t column = 0; column < GUI_FONT_WIDTH; column++)
      if (glyph[row] & (1U << (GUI_FONT_WIDTH - 1 - column)))
        fb_fill_rect(x + column * scale, y + row * scale, scale, scale,
                     color);
}

void gui_draw_text(uint32_t x, uint32_t y, const char *text, uint32_t scale,
                   uint32_t color) {
  uint32_t start_x = x;

  if (!text || scale == 0)
    return;
  while (*text) {
    if (*text == '\n') {
      x = start_x;
      y += (GUI_FONT_HEIGHT + 1) * scale;
    } else {
      gui_draw_char(x, y, *text, scale, color);
      x += (GUI_FONT_WIDTH + 1) * scale;
    }
    text++;
  }
}

uint32_t gui_text_width(const char *text, uint32_t scale) {
  uint32_t width = 0;

  if (!text || scale == 0)
    return 0;
  while (*text && *text != '\n') {
    width += (GUI_FONT_WIDTH + 1) * scale;
    text++;
  }
  return width;
}
